/// Visible column width of `s`, ignoring ANSI SGR escape sequences (one column
/// per character — no wide-glyph handling, fine for the hex/source views).
fn visible_width(s: &str) -> usize {
    let mut width = 0;
    let mut chars = s.chars();
    while let Some(c) = chars.next() {
        if c == '\u{1b}' {
            // Skip the escape sequence up to and including its final letter.
            for c2 in chars.by_ref() {
                if c2.is_ascii_alphabetic() {
                    break;
                }
            }
        } else {
            width += 1;
        }
    }
    width
}

/// Turn cleave's synthetic embedded-binary path segment
/// (`embedded:<kind>[:<name>]@0x<off>`, built in `analyzers::utils`) into a
/// human header label such as `Embedded ELF @ 0x324f9 [2508 bytes]` — or, when
/// the carrier named the payload, `Embedded PE payload.exe @ 0x5010 [2508 bytes]`.
/// Returns `None` for any segment that isn't an embedded-binary marker.
fn embedded_label(segment: &str, size: u64) -> Option<String> {
    let rest = segment.strip_prefix("embedded:")?;
    let (kind_and_name, off) = rest.rsplit_once('@')?;
    let (kind, name) = match kind_and_name.split_once(':') {
        Some((kind, name)) => (kind, Some(name)),
        None => (kind_and_name, None),
    };
    let mut label = format!("Embedded {}", display_file_type(kind));
    if let Some(name) = name {
        label.push(' ');
        label.push_str(name);
    }
    label.push_str(&format!(" @ {off} [{size} bytes]"));
    Some(label)
}

/// Render the rich file header. Plain (cleave): `path  type • formula  legend`.
/// With a [`HeaderBadge`] (an embedding host): a single lean line `stamp path · type
/// trailer`, plus the badge's subtitle beneath. Then a rule sized to the widest
/// line of the header and the `body` it sits above (capped at the terminal).
/// Card-layout member header: ` 📄 path · TYPE · size` — bright path shown
/// relative to the artifact (the container is already named by the caller's
/// header above, so repeating it per member is pure noise), dim type and size,
/// no formula, no severity legend.
fn card_header(out: &mut String, file: &FileAnalysis, colorize: bool) {
    use crate::types::file_analysis::ARCHIVE_DELIMITER;
    // Everything after the first archive delimiter is the artifact-relative
    // member path; deeper nesting reads as `/`.
    let path = match file.path.split_once(ARCHIVE_DELIMITER) {
        Some((_, members)) => members.replace(ARCHIVE_DELIMITER, "/"),
        None => tiny_path(&file.path, true),
    };
    let path = sample_text(&path).into_owned();
    let mut meta = format!("\u{00b7} {}", display_file_type(&file.file_type));
    let size = card_size(file.size);
    if !size.is_empty() {
        meta.push_str(&format!(" \u{00b7} {size}"));
    }
    if colorize {
        out.push_str(&format!(
            " \u{1f4c4} {} {}\n",
            path.bright_white().bold(),
            meta.bright_black(),
        ));
    } else {
        out.push_str(&format!(" \u{1f4c4} {path} {meta}\n"));
    }
}

/// One-decimal human size for card headers (`5.4KB`, `42.6KB`) — matches the
/// artifact header an embedding host prints above, so the two levels read as one system.
fn card_size(bytes: u64) -> String {
    const KB: u64 = 1024;
    const MB: u64 = 1024 * KB;
    const GB: u64 = 1024 * MB;
    match bytes {
        0 => String::new(),
        b if b >= GB => format!("{:.1}GB", b as f64 / GB as f64),
        b if b >= MB => format!("{:.1}MB", b as f64 / MB as f64),
        b if b >= KB => format!("{:.1}KB", b as f64 / KB as f64),
        b => format!("{b}B"),
    }
}

fn rich_header(
    out: &mut String,
    file: &FileAnalysis,
    term_width: usize,
    badge: HeaderBadge<'_>,
    body: &str,
) {
    // A badge means a verdict-led view (an embedding host): keep the header lean — the file
    // type after a `·`, no formula or legend. cleave's own header keeps both.
    let badged = badge.badge.is_some();
    let file_type_display = display_file_type(&file.file_type);
    let display_path = display_path(file);
    // Embedded binaries carry a synthetic `embedded:<kind>@0x<off>` segment; turn
    // it into a self-describing headline so the sub-view reads as a distinct
    // payload of the parent, not a cryptic stray entry.
    let embedded = (file.depth > 0)
        .then(|| embedded_label(&display_path, file.size))
        .flatten();
    let formula = || crate::formula::of(&file.findings).unwrap_or_default();
    let type_display = if badged {
        // The badged verdict view stays lean: type only, no identity/formula.
        format!("\u{00b7} {file_type_display}")
            .bright_black()
            .to_string()
    } else if embedded.is_some() {
        // The kind already leads the embedded headline, so show only the formula.
        let formula = formula();
        if formula.is_empty() {
            String::new()
        } else {
            format!("{} {}", "•".bright_black(), formula.bright_black())
        }
    } else {
        let formula = formula();
        // Header reads `TYPE · <identity headline> • <formula>`. The type and
        // formula stay dim; the identity headline (what · who · trust) renders
        // brighter so "what is this / who signed it" pops at a glance.
        let mut s = file_type_display.bright_black().to_string();
        if let Some(headline) = file
            .identity
            .as_ref()
            .and_then(|id| identity_headline(id, true))
        {
            s.push_str(&format!(" {} {headline}", "·".bright_black()));
        }
        if !formula.is_empty() {
            s.push_str(&format!(
                " {} {}",
                "•".bright_black(),
                formula.bright_black()
            ));
        }
        s
    };
    let label = embedded.as_deref().unwrap_or(&display_path);
    let counts = if badged {
        String::new()
    } else {
        severity_legend(file)
    };
    // A space follows the verdict stamp before the filename. Single spaces
    // separate the rest; cleave's own (unbadged) header keeps its two-space layout.
    let lead = badge.badge.map_or_else(String::new, |b| format!("{b} "));
    let sep = if badged { " " } else { "  " };
    let trail = badge.trailer.map(|t| format!(" {t}")).unwrap_or_default();
    let header_line = format!(
        "{lead}{}{sep}{}{}{}",
        label.bright_white().bold(),
        type_display,
        counts,
        trail,
    );

    out.push_str(&header_line);
    out.push('\n');
    if let Some(sub) = badge.subtitle {
        out.push_str(sub);
        out.push('\n');
    }
    // Nested files (archive members, embedded payloads) skip the divider rule:
    // the indentation already sets them apart, and a rule per member is just
    // clutter. The top-level file keeps its rule as a clear section break.
    if file.depth == 0 {
        // Size the rule to the widest line it divides — the header, its subtitle
        // (measured per line: callers may stack several, e.g. an interpretation
        // above a hash), and the body beneath — so the divider is only as wide
        // as it needs to be.
        let mut rule_w = visible_width(&header_line);
        for line in badge.subtitle.iter().flat_map(|s| s.lines()) {
            rule_w = rule_w.max(visible_width(line));
        }
        for line in body.lines() {
            rule_w = rule_w.max(visible_width(line));
        }
        let rule_w = rule_w.clamp(1, term_width);
        out.push_str(&format!("{}\n", file_rule(rule_w)));
    }
}

/// A compact, colored severity tally for the header: `  3H 2S 4N`, counting each
/// distinct shown finding once. Empty tiers are omitted.
fn severity_legend(file: &FileAnalysis) -> String {
    let (mut hostile, mut susp, mut notable) = (0u32, 0u32, 0u32);
    let mut seen = HashSet::new();
    for f in &file.findings {
        if !tiny_should_show(f, file) || !seen.insert(f.id.as_str()) {
            continue;
        }
        match f.crit {
            Criticality::Hostile => hostile += 1,
            Criticality::Suspicious => susp += 1,
            Criticality::Notable => notable += 1,
            _ => {}
        }
    }
    let mut parts: Vec<String> = Vec::new();
    if hostile > 0 {
        parts.push(paint_by_crit(Criticality::Hostile, &format!("{hostile}H")).to_string());
    }
    if susp > 0 {
        parts.push(paint_by_crit(Criticality::Suspicious, &format!("{susp}S")).to_string());
    }
    if notable > 0 {
        parts.push(paint_by_crit(Criticality::Notable, &format!("{notable}N")).to_string());
    }
    if parts.is_empty() {
        String::new()
    } else {
        format!("   {}", parts.join(" "))
    }
}

fn tiny_should_show(finding: &Finding, file: &FileAnalysis) -> bool {
    if finding.crit != Criticality::Component {
        return true;
    }

    file.findings
        .iter()
        .any(|f| f.trait_refs.iter().any(|id| id == &finding.id))
}

/// Format byte size as human-readable string (compact)
fn format_size(bytes: u64) -> String {
    if bytes == 0 {
        return String::new();
    }
    const KB: u64 = 1024;
    const MB: u64 = 1024 * KB;
    const GB: u64 = 1024 * MB;
    if bytes >= GB {
        format!("{:.1}GB", bytes as f64 / GB as f64)
    } else if bytes >= MB {
        format!("{:.1}MB", bytes as f64 / MB as f64)
    } else if bytes >= KB {
        format!("{}KB", bytes / KB)
    } else {
        format!("{}B", bytes)
    }
}

/// Get terminal width, defaulting to 100 if unavailable. Public so an embedding host can
/// size its card rules to the same width this module sizes rows to.
#[must_use]
pub fn terminal_width() -> usize {
    terminal_size::terminal_size()
        .map(|(w, _)| w.0 as usize)
        .unwrap_or(100)
}

/// Truncate string to max width, using ellipsis (…) if needed
fn truncate_with_ellipsis(s: &str, max_width: usize) -> String {
    if s.len() <= max_width {
        return s.to_string();
    }
    if max_width <= 1 {
        return "…".to_string();
    }
    // Find char boundary for truncation
    let mut end = max_width - 1;
    while !s.is_char_boundary(end) && end > 0 {
        end -= 1;
    }
    format!("{}…", &s[..end])
}

/// A nested file's own name (its last archive segment); a top-level file's
/// full path. Paths come from the sample (archive member names), so their
/// controls and invisible characters are made visible.
fn display_path(file: &FileAnalysis) -> std::borrow::Cow<'_, str> {
    let path = if file.depth == 0 {
        file.path.as_str()
    } else {
        file.path
            .rsplit(crate::types::file_analysis::ARCHIVE_DELIMITER)
            .next()
            .unwrap_or(&file.path)
    };
    sample_text(path)
}

fn display_file_type(file_type: &str) -> String {
    file_type.to_uppercase()
}

/// Full-width slate-blue rule used as a file-boundary marker. Routed
/// through `theme::paint_rule` and `theme::RULE_CHAR` so analyze and
/// diff share the exact same separator.
fn file_rule(width: usize) -> colored::ColoredString {
    let rule: String = crate::theme::RULE_CHAR.to_string().repeat(width);
    crate::theme::paint_rule(rule)
}

