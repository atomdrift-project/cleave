/// JSONL file entry - emitted for each file as it's analyzed
#[allow(dead_code)] // Used by binary target
#[derive(serde::Serialize)]
struct JsonlFileEntry<'a> {
    #[serde(rename = "type")]
    entry_type: &'static str,
    #[serde(flatten)]
    file: &'a crate::types::FileAnalysis,
}

/// JSONL summary entry - emitted at the end of streaming output
#[allow(dead_code)] // Used by binary target
#[derive(serde::Serialize)]
struct JsonlSummary {
    #[serde(rename = "type")]
    entry_type: &'static str,
    files_analyzed: u32,
    #[serde(rename = "x")]
    score: u32,
    hostile: u32,
    suspicious: u32,
    notable: u32,
    duration_ms: u64,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    tools: Vec<String>,
}

/// Minimum confidence required for a finding to contribute to the formula.
/// Higher than the display threshold (0.5) on purpose: the formula is a
/// fingerprint, not an enumeration, so we want only findings the analyzer
/// is confident about.
pub(crate) const FORMULA_MIN_CONF: f32 = 0.65;

/// Canonical filter for formula generation: aggregate by directory, keep
/// notable-or-higher findings with confidence ≥ FORMULA_MIN_CONF.
///
/// Component- and baseline-criticality findings are intentionally dropped:
/// the formula is meant to mirror the CLI's notable-or-higher display, so
/// the JSON `f` field, JSONL `f` field, library `formula_from_report`, and
/// terminal header all share this single source of truth.
pub(crate) fn filter_findings_for_formula(findings: &[Finding]) -> Vec<Finding> {
    let aggregated = aggregate_findings_by_directory(findings);
    aggregated
        .into_iter()
        .filter(|f| f.crit >= Criticality::Notable && f.conf >= FORMULA_MIN_CONF)
        .collect()
}

/// Format a single file analysis as a JSONL line
#[allow(dead_code)] // Used by binary target
pub(crate) fn format_jsonl_line(file: &crate::types::FileAnalysis) -> Result<String> {
    // Compute formula if not already set
    if file.formula.is_none() {
        let mut file_with_formula = file.clone();
        let filtered = filter_findings_for_formula(&file.findings);
        let formula = malecule_bridge::formula_from_findings(&filtered);
        file_with_formula.formula = Some(if formula.is_empty() {
            "∅".to_string()
        } else {
            formula
        });
        let entry = JsonlFileEntry {
            entry_type: "file",
            file: &file_with_formula,
        };
        return Ok(serde_json::to_string(&entry)?);
    }

    let entry = JsonlFileEntry {
        entry_type: "file",
        file,
    };
    Ok(serde_json::to_string(&entry)?)
}

/// Format the summary as a JSONL line (for end of streaming output)
#[allow(dead_code)] // Used by binary target
pub(crate) fn format_jsonl_summary(report: &AnalysisReport) -> Result<String> {
    let summary = report.summary.as_ref();
    let counts = summary.map(|s| &s.counts);

    let entry = JsonlSummary {
        entry_type: "summary",
        files_analyzed: summary
            .map(|s| s.files_analyzed)
            .unwrap_or(report.files.len() as u32),
        score: summary.map(|s| s.score).unwrap_or(0),
        hostile: counts.map(|c| c.hostile).unwrap_or(0),
        suspicious: counts.map(|c| c.suspicious).unwrap_or(0),
        notable: counts.map(|c| c.notable).unwrap_or(0),
        duration_ms: summary
            .map(|s| s.duration_ms)
            .unwrap_or(report.metadata.analysis_duration_ms),
        tools: summary
            .map(|s| s.tools.clone())
            .unwrap_or_else(|| report.metadata.tools_used.clone()),
    };
    Ok(serde_json::to_string(&entry)?)
}

/// Format entire report as JSONL (for non-streaming output)
#[allow(dead_code)] // Used by binary target
pub(crate) fn format_jsonl(report: &AnalysisReport) -> Result<String> {
    let mut lines = Vec::with_capacity(report.files.len() + 1);

    // Emit each file as a line
    for file in &report.files {
        lines.push(format_jsonl_line(file)?);
    }

    // Emit summary at end
    lines.push(format_jsonl_summary(report)?);

    // Join with newlines and add trailing newline for proper JSONL streaming
    Ok(format!("{}\n", lines.join("\n")))
}

/// Format the report as compact, context-centric text for small LLMs.
///
/// Reuses two conventions every model already knows: `grep -n -C2` for content
/// (`N:` = a matched line, `N-` = surrounding context, `--` = a gap) and the
/// compiler diagnostic (`# SEV id desc`) for findings. A location `N` is a
/// 1-based line number for source, or a hex byte offset for binaries and
/// minified one-liners. Findings with no positional anchor render as `.` lines.
///
/// ```text
/// # ctx: N: hit, N- context, -- gap, . no-loc; src text | hex ascii; trailer # H/S/N/B/C/F id desc
/// evil.sh <TAB> sh 4.2KB 142
/// 19- def run():
/// 20: exec(base64.b64decode(p)) # H exec/eval-b64 decode+exec base64
/// .        # N metadata/unsigned unsigned binary
/// ```
#[allow(dead_code)] // Used by the binary target via --format tiny.
pub(crate) fn format_tiny(report: &AnalysisReport) -> String {
    if !report.files.iter().any(file_has_output) {
        return String::new();
    }

    let mut out = String::with_capacity(4096);
    out.push_str(
        "# ctx: N: hit, N- context, -- gap, . no-loc; src text | hex ascii; trailer # H/S/N/B/C/F id desc\n",
    );

    for file in &report.files {
        if !file_has_output(file) {
            continue;
        }

        // File header: path \t type size score
        out.push_str(&tiny_field(&file.path));
        out.push('\t');
        out.push_str(&tiny_field(&file.file_type));
        out.push(' ');
        out.push_str(&format_size(file.size));
        out.push(' ');
        out.push_str(&file.score.to_string());
        out.push('\n');

        let shown = shown_ids(file);
        render_context_lines(&mut out, file, &shown);
        render_no_anchor_findings(&mut out, file, &shown);
    }

    out
}

/// Whether a file contributes anything to tiny output.
fn file_has_output(file: &FileAnalysis) -> bool {
    file.findings.iter().any(|f| tiny_should_show(f, file))
}

/// Finding ids in this file that should be shown.
fn shown_ids(file: &FileAnalysis) -> HashSet<&str> {
    file.findings
        .iter()
        .filter(|f| tiny_should_show(f, file))
        .map(|f| f.id.as_str())
        .collect()
}

/// Emit the merged context: `grep -n -C2`-style lines with `# SEV id desc`
/// trailers, `--` between non-contiguous windows.
fn render_context_lines(out: &mut String, file: &FileAnalysis, shown: &HashSet<&str>) {
    let mut prev: Option<u64> = None;
    for line in &file.context {
        let notes: Vec<&Note> = line
            .notes
            .iter()
            .filter(|n| shown.contains(n.id.as_str()))
            .collect();

        // Consecutive units differ by 1 for source lines, 16 for hex rows;
        // a larger jump is a gap between windows.
        let step = if line.hex { 16 } else { 1 };
        if prev.is_some_and(|p| line.loc > p.saturating_add(step)) {
            out.push_str("--\n");
        }
        prev = Some(line.loc);

        if line.hex {
            out.push_str(&format!("{:x}", line.loc));
        } else {
            out.push_str(&line.loc.to_string());
        }
        out.push(if notes.is_empty() { '-' } else { ':' });
        out.push(' ');
        out.push_str(&line.text);

        // First finding trails the content; any others get their own lines so
        // the content is shown exactly once.
        if let Some((first, rest)) = notes.split_first() {
            out.push_str(" # ");
            out.push_str(&note_str(first));
            out.push('\n');
            for n in rest {
                out.push_str("# ");
                out.push_str(&note_str(n));
                out.push('\n');
            }
        } else {
            out.push('\n');
        }
    }
}

/// Emit shown findings that have no positional anchor (imports, metric/size
/// thresholds, structural facts) as `.` lines.
fn render_no_anchor_findings(out: &mut String, file: &FileAnalysis, shown: &HashSet<&str>) {
    let anchored: HashSet<&str> = file
        .context
        .iter()
        .flat_map(|l| l.notes.iter().map(|n| n.id.as_str()))
        .collect();

    let mut rest: Vec<&Finding> = file
        .findings
        .iter()
        .filter(|f| shown.contains(f.id.as_str()) && !anchored.contains(f.id.as_str()))
        .collect();
    rest.sort_unstable_by(|a, b| b.crit.cmp(&a.crit).then_with(|| a.id.cmp(&b.id)));

    let mut seen = HashSet::new();
    for f in rest {
        if !seen.insert(f.id.as_str()) {
            continue;
        }
        out.push_str(". # ");
        out.push(f.crit.letter());
        out.push(' ');
        out.push_str(&f.id);
        if !f.desc.is_empty() {
            out.push(' ');
            out.push_str(&terse_description(&f.desc));
        }
        out.push('\n');
    }
}

/// Render a note as `SEV id desc` (the part after `# `).
fn note_str(n: &Note) -> String {
    let mut s = String::new();
    s.push(n.crit.letter());
    s.push(' ');
    s.push_str(&n.id);
    if !n.desc.is_empty() {
        s.push(' ');
        s.push_str(&terse_description(&n.desc));
    }
    s
}

fn tiny_field(value: &str) -> String {
    value.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn tiny_should_show(finding: &Finding, file: &FileAnalysis) -> bool {
    if finding.crit != Criticality::Component {
        return true;
    }

    file.findings
        .iter()
        .any(|f| f.trait_refs.iter().any(|id| id == &finding.id))
}

/// Format byte size as human-readable string (compact)
fn format_size(bytes: u64) -> String {
    if bytes == 0 {
        return String::new();
    }
    const KB: u64 = 1024;
    const MB: u64 = 1024 * KB;
    const GB: u64 = 1024 * MB;
    if bytes >= GB {
        format!("{:.1}GB", bytes as f64 / GB as f64)
    } else if bytes >= MB {
        format!("{:.1}MB", bytes as f64 / MB as f64)
    } else if bytes >= KB {
        format!("{}KB", bytes / KB)
    } else {
        format!("{}B", bytes)
    }
}

/// Parse JSONL (newline-delimited JSON) back to AnalysisReport
#[allow(dead_code)] // Used by binary target
pub(crate) fn parse_jsonl(jsonl: &str) -> Result<AnalysisReport> {
    let mut files = Vec::new();
    let mut summary = None;
    let mut version = "3".to_string();

    // Parse each line as a JSON entry
    for line in jsonl.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() {
            continue;
        }

        let value: serde_json::Value = serde_json::from_str(trimmed)?;
        let entry_type = value.get("type").and_then(|v| v.as_str());

        match entry_type {
            Some("file") => {
                let file: crate::types::FileAnalysis = serde_json::from_value(value)?;
                files.push(file);
            }
            Some("summary") => {
                if let Some(v) = value
                    .get("version")
                    .or_else(|| value.get("schema_version"))
                    .and_then(|v| v.as_str())
                {
                    version = v.to_string();
                }
                let tools: Vec<String> = value
                    .get("tools")
                    .or_else(|| value.get("tools_used"))
                    .and_then(|v| v.as_array())
                    .map(|arr| {
                        arr.iter()
                            .filter_map(|v| v.as_str().map(str::to_string))
                            .collect()
                    })
                    .unwrap_or_default();
                let errors: Vec<String> = value
                    .get("errors")
                    .and_then(|v| v.as_array())
                    .map(|arr| {
                        arr.iter()
                            .filter_map(|v| v.as_str().map(str::to_string))
                            .collect()
                    })
                    .unwrap_or_default();
                let duration_ms = value
                    .get("duration_ms")
                    .or_else(|| value.get("analysis_duration_ms"))
                    .and_then(serde_json::Value::as_u64)
                    .unwrap_or(0);

                summary = Some(crate::types::ReportSummary {
                    files_analyzed: value
                        .get("files_analyzed")
                        .and_then(serde_json::Value::as_u64)
                        .unwrap_or(files.len() as u64) as u32,
                    counts: crate::types::FindingCounts {
                        hostile: value
                            .get("hostile")
                            .and_then(serde_json::Value::as_u64)
                            .unwrap_or(0) as u32,
                        suspicious: value
                            .get("suspicious")
                            .and_then(serde_json::Value::as_u64)
                            .unwrap_or(0) as u32,
                        notable: value
                            .get("notable")
                            .and_then(serde_json::Value::as_u64)
                            .unwrap_or(0) as u32,
                    },
                    score: 0,
                    duration_ms,
                    tools,
                    errors,
                });
            }
            _ => {
                // Unknown entry type, skip
            }
        }
    }

    // Create a minimal AnalysisReport with the parsed data
    let target = if let Some(first_file) = files.first() {
        crate::types::TargetInfo {
            path: first_file.path.clone(),
            file_type: first_file.file_type.clone(),
            sha256: first_file.sha256.clone(),
            size_bytes: first_file.size,
            architectures: None,
        }
    } else {
        crate::types::TargetInfo {
            path: "unknown".to_string(),
            file_type: "unknown".to_string(),
            sha256: String::new(),
            size_bytes: 0,
            architectures: None,
        }
    };

    let mut report = AnalysisReport::new(target);
    report.version = version;
    report.files = files;
    report.summary = summary;

    Ok(report)
}

/// Get terminal width, defaulting to 100 if unavailable
#[allow(dead_code)] // Used by binary target
fn terminal_width() -> usize {
    terminal_size::terminal_size()
        .map(|(w, _)| w.0 as usize)
        .unwrap_or(100)
}

/// Truncate string to max width, using ellipsis (…) if needed
#[allow(dead_code)] // Used by binary target
fn truncate_with_ellipsis(s: &str, max_width: usize) -> String {
    if s.len() <= max_width {
        return s.to_string();
    }
    if max_width <= 1 {
        return "…".to_string();
    }
    // Find char boundary for truncation
    let mut end = max_width - 1;
    while !s.is_char_boundary(end) && end > 0 {
        end -= 1;
    }
    format!("{}…", &s[..end])
}

fn display_file_type(file_type: &str) -> String {
    file_type.to_uppercase()
}

/// Render a section label as a muted 256-color pill — bold white on dark bg.
/// Hue encodes the namespace: red=well-known, magenta=objectives, blue=behaviors, gray=metadata.
#[allow(dead_code)] // Used by binary target
fn section_pill(ns: &Namespace) -> colored::ColoredString {
    let (name, r, g, b) = match ns {
        Namespace::WellKnown => (ns.display_name(), 95, 0, 0), // dark red (256 idx 52)
        Namespace::Objectives => (ns.display_name(), 95, 0, 95), // dark magenta (53)
        Namespace::MicroBehaviors => (ns.display_name(), 0, 0, 95), // dark blue (17)
        Namespace::Metadata => (ns.display_name(), 48, 48, 48), // dark gray (236)
        Namespace::ThirdParty => (ns.display_name(), 120, 56, 0), // dark orange
    };
    format!(" {name} ").bold().white().on_truecolor(r, g, b)
}

/// Full-width slate-blue rule used as a file-boundary marker. Routed
/// through `theme::paint_rule` and `theme::RULE_CHAR` so analyze and
/// diff share the exact same separator.
#[allow(dead_code)] // Used by binary target
fn file_rule(width: usize) -> colored::ColoredString {
    let rule: String = crate::theme::RULE_CHAR.to_string().repeat(width);
    crate::theme::paint_rule(rule)
}

/// Bullet indicator based on criticality: • notable, •• suspicious, ••• hostile
#[allow(dead_code)] // Used by binary target
fn bullet_for_crit(crit: &Criticality) -> colored::ColoredString {
    use crate::theme;
    match crit {
        Criticality::Hostile => theme::paint_hostile("•••"),
        Criticality::Suspicious => theme::paint_suspicious(" ••"),
        _ => theme::paint_baseline("  •"),
    }
}

/// Colorize text based on criticality.
#[allow(dead_code)] // Used by binary target
fn colorize_by_crit(text: &str, crit: &Criticality) -> colored::ColoredString {
    use crate::theme;
    match crit {
        Criticality::Hostile => theme::paint_hostile(text),
        Criticality::Suspicious => theme::paint_suspicious(text),
        _ => theme::paint_baseline(text),
    }
}

/// Extract short trait ID (strip namespace prefix)
/// e.g., "well-known/malware/BPFDoor" -> "BPFDoor"
/// e.g., "objectives/c2/http/beacon" -> "c2/http/beacon"
/// e.g., "micro-behaviors/fs/read/file" -> "fs/read/file"
#[allow(dead_code)] // Used by binary target
fn short_trait_id(id: &str) -> String {
    let parts: Vec<&str> = id.split('/').collect();
    if parts.len() > 1 {
        // Skip namespace prefix (well-known, objectives, micro-behaviors)
        let first = parts[0];
        if first == "well-known"
            || first == "objectives"
            || first == "micro-behaviors"
            || first == "metadata"
            || first == "third_party"
            || first == "third-party"
        {
            return parts[1..].join("/");
        }
    }
    id.to_string()
}

/// Format analysis report for terminal display
/// Uses the v2 flat files array structure.
#[allow(dead_code)] // Used by binary target
pub(crate) fn format_terminal(report: &AnalysisReport) -> String {
    let mut output = String::new();
    let term_width = terminal_width();

    // Iterate over files that have findings
    for file in &report.files {
        // Skip files with no findings
        if file.findings.is_empty() {
            continue;
        }

        // Per RULES.md: components are hidden from terminal output unless a
        // matched composite that references them fires. Build the set of
        // component IDs referenced by notable-or-higher composites, then keep
        // components only when they appear in that set.
        let referenced_component_ids: HashSet<&str> = file
            .findings
            .iter()
            .filter(|f| f.crit >= Criticality::Notable && f.conf >= 0.5)
            .flat_map(|f| f.trait_refs.iter().map(String::as_str))
            .collect();

        let pre_filtered: Vec<Finding> = file
            .findings
            .iter()
            .filter(|f| f.conf >= 0.5)
            .filter(|f| {
                f.crit >= Criticality::Notable
                    || (f.crit == Criticality::Component
                        && referenced_component_ids.contains(f.id.as_str()))
            })
            .cloned()
            .collect();

        // Aggregate remaining findings by directory path
        let filtered = aggregate_findings_by_directory(&pre_filtered);

        if filtered.is_empty() {
            continue;
        }

        // Group findings by namespace
        let mut by_namespace: HashMap<Namespace, Vec<&Finding>> = HashMap::new();
        for finding in &filtered {
            if let Some(ns) = Namespace::from_trait_id(&finding.id) {
                by_namespace.entry(ns).or_default().push(finding);
            }
        }

        // Sort findings within each namespace by criticality (hostile first)
        for findings in by_namespace.values_mut() {
            findings.sort_unstable_by(|a, b| b.crit.cmp(&a.crit).then_with(|| a.id.cmp(&b.id)));
        }

        // Pre-calculate column widths across ALL findings in this file
        let all_findings: Vec<&&Finding> = by_namespace.values().flat_map(|v| v.iter()).collect();

        let trait_width = all_findings
            .iter()
            .map(|f| short_trait_id(&f.id).len())
            .max()
            .unwrap_or(20);

        let natural_desc_width = all_findings
            .iter()
            .map(|f| terse_description(&f.desc).len())
            .max()
            .unwrap_or(30);

        // Reserve at least MIN_EVIDENCE_WIDTH columns for evidence by capping the
        // description column. One overly long description would otherwise push
        // evidence off the screen, leaving every row with just a stray `…`.
        // Layout overhead: bullet(3) + space(1) + trait + 2 spaces + 2 spaces = 8 + trait_width
        // 24 cols accommodates two short kv-array members like
        // `[lzma_crc32, lzma_crc64]` — descriptions truncate hard
        // first since they're often paraphrasable from the trait id.
        const MIN_EVIDENCE_WIDTH: usize = 24;
        let overhead = 8 + trait_width;
        let max_desc_width = term_width.saturating_sub(overhead + MIN_EVIDENCE_WIDTH);
        let desc_width = natural_desc_width.min(max_desc_width);

        let evidence_width = term_width.saturating_sub(overhead + desc_width);

        // Generate formula from the canonical formula filter (not the
        // display-aggregated `filtered` set above, which includes referenced
        // components). Keeps the header formula identical to the JSON `f`.
        let formula_findings = filter_findings_for_formula(&file.findings);
        let formula = malecule_bridge::formula_from_findings(&formula_findings);

        let file_type_display = display_file_type(&file.file_type);

        // File header: [indent] path  type • formula
        let type_formula = if formula.is_empty() {
            file_type_display
        } else {
            format!("{} • {}", file_type_display, formula)
        };

        // Indent nested files (archive members, embedded binaries, decoded payloads)
        let indent = "  ".repeat(file.depth as usize);
        // Strip virtual path prefixes (!!member, ##encoding) for display if depth > 0
        let display_path = if file.depth > 0 {
            file.path
                .rsplit(crate::types::file_analysis::ARCHIVE_DELIMITER)
                .next()
                .or_else(|| {
                    file.path
                        .rsplit(crate::types::file_analysis::ENCODING_DELIMITER)
                        .next()
                })
                .unwrap_or(&file.path)
        } else {
            &file.path
        };

        output.push_str(&format!(
            "{}{}  {}\n",
            indent,
            display_path.bright_white().bold(),
            type_formula.bright_black()
        ));
        let rule_width = term_width.saturating_sub(indent.len());
        output.push_str(&format!("{}{}\n", indent, file_rule(rule_width)));

        // Render namespaces in fixed order: WELL-KNOWN, OBJECTIVES, MICRO-BEHAVIORS, METADATA, THIRD-PARTY.
        // First section follows the file rule with no gap; later sections get a leading blank.
        let mut first_section = true;
        for ns in [
            Namespace::WellKnown,
            Namespace::Objectives,
            Namespace::MicroBehaviors,
            Namespace::Metadata,
            Namespace::ThirdParty,
        ] {
            let Some(findings) = by_namespace.get(&ns) else {
                continue; // Skip empty sections
            };

            if !first_section {
                output.push('\n');
            }
            first_section = false;

            output.push_str(&format!("{}\n", section_pill(&ns)));

            // Bullet (3) + space (1) + trait + 2 spaces + desc + 2 spaces.
            // Continuation lines for multi-line evidence start at this column.
            let evidence_col = 3 + 1 + trait_width + 2 + desc_width + 2;
            let evidence_indent = " ".repeat(evidence_col);
            // Cap multi-line evidence so a single huge match doesn't drown
            // the rest of the output. Beyond the cap, the last visible line
            // gets a trailing ellipsis.
            const MAX_EVIDENCE_LINES: usize = 4;

            // Render each finding
            for finding in findings {
                let trait_id = short_trait_id(&finding.id);
                let desc = terse_description(&finding.desc);
                let evidence = format_evidence(finding);

                // Build the line with proper column alignment
                // Format: ● trait_id  description  evidence
                let bullet = bullet_for_crit(&finding.crit);
                let padded_trait = format!("{:width$}", trait_id, width = trait_width);
                let truncated_desc = truncate_with_ellipsis(&desc, desc_width);
                let padded_desc = format!("{:width$}", truncated_desc, width = desc_width);

                let raw_lines: Vec<&str> = evidence.lines().collect();
                let (visible_lines, overflow) = if raw_lines.len() > MAX_EVIDENCE_LINES {
                    (&raw_lines[..MAX_EVIDENCE_LINES], true)
                } else {
                    (&raw_lines[..], false)
                };

                if visible_lines.is_empty() {
                    output.push_str(&format!(
                        "{} {}  {}\n",
                        bullet,
                        padded_trait,
                        colorize_by_crit("", &finding.crit)
                    ));
                    continue;
                }

                for (i, line) in visible_lines.iter().enumerate() {
                    let truncated = truncate_with_ellipsis(line, evidence_width);
                    let colored = colorize_by_crit(&truncated, &finding.crit);

                    if i == 0 {
                        output.push_str(&format!(
                            "{} {}  {}  {}\n",
                            bullet, padded_trait, padded_desc, colored
                        ));
                    } else {
                        output.push_str(&format!("{}{}\n", evidence_indent, colored));
                    }
                }
                // Overflow indicator on its own line: dimmed `…` at the
                // evidence column. Unambiguous "more lines below were
                // dropped" without doubling up with per-line truncation
                // ellipses.
                if overflow {
                    output.push_str(&format!(
                        "{}{}\n",
                        evidence_indent,
                        colorize_by_crit("…", &finding.crit)
                    ));
                }
            }
        }

        // Trailing blank after all sections separates this file from the next.
        output.push('\n');
    }

    output
}

