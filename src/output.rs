/// Extract base trait ID for aggregation (strip ::variant suffix)
/// e.g., "well-known/malware/trojan/macos-stealer-cpp::variant" -> "well-known/malware/trojan/macos-stealer-cpp"
/// e.g., "objectives/credential-access/stealer/shell::system-wide" -> "objectives/credential-access/stealer/shell"
/// Trait IDs without a variant suffix are returned unchanged.
#[allow(dead_code)] // Used by binary target
#[must_use]
fn get_directory_path(id: &str) -> String {
    // Strip variant suffix (::variant) if present
    // The base trait ID (without variant) is used as the aggregation key
    id.split("::").next().unwrap_or(id).to_string()
}

/// Aggregated finding for a directory path
#[allow(dead_code)] // Used by binary target
#[derive(Clone)]
struct AggregatedFinding {
    /// The directory path (e.g., "execution/command/subprocess")
    directory: String,
    /// The best (highest criticality) finding
    best: Finding,
    /// All trait IDs that matched in this directory
    matched_traits: Vec<String>,
}

/// Aggregate findings by directory path, keeping highest criticality (then highest conf)
/// Returns findings with IDs set to directory paths and trait_refs containing all matched trait IDs
/// Internal findings (from code analyzers) are not aggregated - shown individually
#[allow(dead_code)] // Used by binary target
#[must_use]
pub(crate) fn aggregate_findings_by_directory(findings: &[Finding]) -> Vec<Finding> {
    let mut aggregated: HashMap<String, AggregatedFinding> = HashMap::new();
    let mut internal_findings = Vec::new();

    for finding in findings {
        // YAML traits with variants (containing "::") are always aggregated
        // Even if they have evidence from internal sources (like symbol matching)
        let has_variant_suffix = finding.id.contains("::");

        // Check if this is an internal finding (generated by code, not from YAML traits)
        let is_internal = !has_variant_suffix
            && !finding.evidence.is_empty()
            && finding.evidence.iter().any(|e| {
                // Internal sources (generated by analyzers, not from YAML traits)
                e.source == "codesign_parser"
                    || e.source == "binary_analyzer"
                    || e.source == "strings_extractor"
                    || e.source == "import_mapper"
            });

        // Internal findings bypass aggregation - they're shown individually
        if is_internal {
            internal_findings.push(finding.clone());
            continue;
        }

        let dir_path = get_directory_path(&finding.id);

        match aggregated.get_mut(&dir_path) {
            None => {
                aggregated.insert(
                    dir_path.clone(),
                    AggregatedFinding {
                        directory: dir_path,
                        best: finding.clone(),
                        matched_traits: vec![finding.id.clone()],
                    },
                );
            }
            Some(agg) => {
                // Add this trait ID to the list
                if !agg.matched_traits.contains(&finding.id) {
                    agg.matched_traits.push(finding.id.clone());
                }

                // Keep the one with higher criticality.
                // Ties: higher confidence, then lexicographically smaller id so
                // parallel trait evaluation order doesn't flip the displayed pick.
                let should_replace = finding.crit > agg.best.crit
                    || (finding.crit == agg.best.crit && finding.conf > agg.best.conf)
                    || (finding.crit == agg.best.crit
                        && finding.conf == agg.best.conf
                        && finding.id < agg.best.id);

                if should_replace {
                    agg.best = finding.clone();
                }
            }
        }
    }

    // Convert aggregated findings to Finding structs with directory as ID
    let mut result: Vec<Finding> = aggregated
        .into_values()
        .map(|agg| {
            let mut result = agg.best;
            result.id = agg.directory;
            result.trait_refs = agg.matched_traits;
            result
        })
        .collect();

    // Add internal findings (not aggregated) to the result
    result.extend(internal_findings);
    result
}

/// Get risk indicator based on criticality
#[allow(dead_code)] // Used by binary target
fn risk_indicator(crit: &Criticality) -> colored::ColoredString {
    use crate::theme;
    match crit {
        Criticality::Filtered => "   ".normal(),
        Criticality::Component => "  ·".dimmed(),
        Criticality::Baseline => theme::paint_baseline("  •"),
        Criticality::Notable => theme::paint_notable("  •"),
        Criticality::Suspicious => theme::paint_suspicious(" ••"),
        Criticality::Hostile => theme::paint_hostile("•••"),
    }
}

/// Get risk level name
/// Split trait ID into namespace and rest, skipping "cap"/"obj" prefixes
/// e.g., "micro-behaviors/execution/command/subprocess" -> ("exec", "command/subprocess")
/// e.g., "objectives/anti-analysis/debugger/detect" -> ("anti-analysis", "debugger/detect")
/// e.g., "intel/discover/process/getuid" -> ("intel", "discover/process/getuid")
#[allow(dead_code)] // Used by binary target
fn split_trait_id(id: &str) -> (String, String) {
    let parts: Vec<&str> = id.split('/').collect();

    // Skip "cap" or "obj" prefix if present
    let start_idx = if parts.len() > 1 && (parts[0] == "cap" || parts[0] == "obj") {
        1
    } else {
        0
    };

    if parts.len() > start_idx + 1 {
        (
            parts[start_idx].to_string(),
            parts[start_idx + 1..].join("/"),
        )
    } else if parts.len() > start_idx {
        (parts[start_idx].to_string(), parts[start_idx].to_string())
    } else {
        (id.to_string(), id.to_string())
    }
}

/// Namespace categories for grouping findings
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[allow(dead_code)] // Used by binary target
enum Namespace {
    WellKnown,
    Objectives,
    MicroBehaviors,
    Metadata,
    ThirdParty,
}

impl Namespace {
    /// Parse namespace from trait ID prefix
    fn from_trait_id(id: &str) -> Option<Self> {
        let prefix = id.split('/').next()?;
        match prefix {
            "well-known" => Some(Self::WellKnown),
            "objectives" => Some(Self::Objectives),
            "micro-behaviors" => Some(Self::MicroBehaviors),
            "metadata" => Some(Self::Metadata),
            "third_party" | "third-party" => Some(Self::ThirdParty),
            _ => None,
        }
    }

    /// Display name for section header
    fn display_name(&self) -> &'static str {
        match self {
            Self::WellKnown => "WELL-KNOWN",
            Self::Objectives => "OBJECTIVES",
            Self::MicroBehaviors => "MICRO-BEHAVIORS",
            Self::Metadata => "METADATA",
            Self::ThirdParty => "THIRD-PARTY",
        }
    }
}

/// Get sort order for namespace (fixed order: well-known, objectives, micro-behaviors, metadata, third-party)
#[allow(dead_code)] // Used by binary target
fn namespace_sort_order(ns: &str) -> u8 {
    match ns {
        "well-known" => 0,
        "objectives" => 1,
        "micro-behaviors" => 2,
        "metadata" => 3,
        "third-party" | "third_party" => 4,
        _ => 5, // Unknown namespaces go last
    }
}

