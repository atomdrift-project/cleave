/// Make descriptions more terse by removing redundant explanatory parentheticals
#[allow(dead_code)] // Used by binary target
fn terse_description(desc: &str) -> String {
    // Remove common verbose patterns that are redundant given the context
    desc.replace(" (timing attacks or sandbox detection)", "")
        .replace(" (C2 communication pattern)", "")
        .replace(" (comprehensive stealer)", "")
        .replace(" (monolithic multicall binary)", "")
        .replace(" (packer pattern)", "")
        .replace(" (potential stealer)", "")
        .replace(" (potential keylogger)", "")
        .replace(" (hardcoded alphabet + decode table)", "")
        .replace(" reveals directory contents", "")
        .replace(" (opendir + readdir + stat)", "")
        .replace(".DS_Store ", "")
        .replace(" (excluding known legitimate)", "")
        .trim()
        .to_string()
}

/// Append the trait/finding id to a plain-view annotation so an LLM reading tiny
/// output can name the exact trait that fired and locate its file: `desc (id)`,
/// or a bare `id` when the description is empty. Plain (LLM/tiny) render paths
/// only — the colored terminal views omit the id to keep the aligned comment
/// gutter legible.
#[allow(dead_code)] // Used by binary target
fn annotate_desc(desc: &str, id: &str) -> String {
    if desc.is_empty() {
        id.to_string()
    } else {
        format!("{desc} ({id})")
    }
}

#[allow(dead_code)] // Used by binary target
fn format_evidence(finding: &Finding) -> String {
    // Dedupe values, drop blank/whitespace-only lines from each. If any
    // value spans multiple lines after cleaning, return the full set as a
    // newline-separated block (the renderer indents continuation lines to
    // the evidence column). Otherwise comma-join for compactness.
    let mut seen = std::collections::HashSet::new();
    let values: Vec<String> = finding
        .evidence
        .iter()
        .filter_map(|e| {
            let cleaned: String = e
                .value
                .lines()
                .filter(|l| !l.trim().is_empty())
                .collect::<Vec<_>>()
                .join("\n");
            if cleaned.is_empty() {
                return None;
            }
            if seen.insert(cleaned.clone()) {
                Some(cleaned)
            } else {
                None
            }
        })
        .take(5)
        .collect();

    if values.is_empty() {
        return String::new();
    }

    if values.iter().any(|v| v.contains('\n')) {
        values.join("\n")
    } else {
        values.join(", ")
    }
}

